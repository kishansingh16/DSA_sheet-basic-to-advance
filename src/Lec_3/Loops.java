package Lec_3;

public class Loops {
    public static void main(String [] args){
        for (int i=0;i<5;i++){
            System.out.println(i);
        }
        for(int j=0;j<5;j=j+2){
            System.out.println(j+1);
        }
        for(int k=10;k>=0;k--){
            System.out.println(k);
        }
    }
}
